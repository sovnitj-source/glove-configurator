#!/usr/bin/env python3
"""
Builds the 3D-view model from the AI reconstruction.

Inputs (see RESEARCH_3D.md):
  research/3d-ai/hunyuan3d-2mv_glove.glb   mesh generated by Hunyuan3D-2mv from our 3 photos
  research/3d-ai/fitted_cameras.json       camera fitted to each photo by silhouette matching
  src/assets/views/back/...                back-view masks (panel labels) + canvas size

Outputs (src/assets/model/):
  glove.glb    centred, unit-scaled mesh with normals. COLOR_0 encodes per-vertex data:
                 R = panel label (index into LABELS) / 255
                 G = 1 if the vertex is visible from the back camera
  model.json   back-camera projection (mesh space -> back canvas pixels), labels, stats

Only the back photo is used for projection: the AI mesh matches it (silhouette IoU ~0.9);
side and palm do not match the mesh (see RESEARCH_3D.md), so their photos are not projected.

Usage: python3 tools/build_model.py      (needs numpy, pillow, scipy, trimesh)
"""
import json
from pathlib import Path

import numpy as np
import trimesh
from PIL import Image
from scipy import ndimage as nd, optimize
from scipy.spatial import cKDTree
from scipy.spatial.transform import Rotation as Rot

ROOT = Path(__file__).resolve().parent.parent
SRC_MESH = ROOT / "research/3d-ai/hunyuan3d-2mv_glove.glb"
CAMS = ROOT / "research/3d-ai/fitted_cameras.json"
VIEW = ROOT / "src/assets/views/back"
OUT = ROOT / "src/assets/model"

LABELS = ["Base", "BOH", "Fingers", "Palm", "Web", "Welting", "Binding", "Laces",
          "Palm Liner", "Swoosh", "Swoosh Stitching", "Swoosh Base", "Embroidery"]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    mesh = trimesh.load(SRC_MESH).to_geometry()
    mesh.merge_vertices()
    # keep the main body + attached laces; drop tiny floating fragments
    parts = sorted(mesh.split(only_watertight=False), key=lambda p: len(p.faces), reverse=True)
    mesh = trimesh.util.concatenate([p for p in parts if len(p.faces) > 150])
    mesh.apply_translation(-mesh.bounding_box.centroid)
    mesh.apply_scale(1.0 / mesh.extents.max())

    manifest = json.loads((VIEW / "manifest.json").read_text())
    W, H = manifest["canvas"]["width"], manifest["canvas"]["height"]
    masks = {k: np.asarray(Image.open(VIEW / p).convert("RGBA"))[..., 3] / 255.0 for k, p in manifest["masks"].items()}
    union = np.clip(sum(m for k, m in masks.items() if k != "Embroidery"), 0, 1) > 0.5

    # camera axes in mesh space (image x = right, image y = down, forward points at the camera)
    R = Rot.from_euler("YXZ", json.loads(CAMS.read_text())["back"]["euler_YXZ"], degrees=True).as_matrix()
    right, up, fwd = R[0], R[1], R[2]

    pts, fi = trimesh.sample.sample_surface(mesh, 1_500_000, seed=3)
    px_r, px_u, px_f = pts @ right, pts @ up, pts @ fwd

    # ---- 2D mapping (uniform scale + offset) from projected mesh to back canvas pixels ----
    ys, xs = np.where(union)

    def sil(params, step=2):
        a, bx, by = params
        ix = ((a * px_r + bx) / step).astype(int)
        iy = ((a * -px_u + by) / step).astype(int)
        h, w = H // step, W // step
        ok = (ix >= 0) & (ix < w) & (iy >= 0) & (iy < h)
        img = np.zeros((h, w), bool)
        img[iy[ok], ix[ok]] = True
        return nd.binary_closing(img, iterations=2)

    tgt = union[::2, ::2][: H // 2, : W // 2]
    a0 = ((xs.max() - xs.min()) / np.ptp(px_r) + (ys.max() - ys.min()) / np.ptp(px_u)) / 2
    bx0 = (xs.max() + xs.min()) / 2 - a0 * (px_r.max() + px_r.min()) / 2
    by0 = (ys.max() + ys.min()) / 2 + a0 * (px_u.max() + px_u.min()) / 2
    iou = lambda p: (sil(p) & tgt).sum() / max((sil(p) | tgt).sum(), 1)
    r = optimize.minimize(lambda p: -iou(p), [a0, bx0, by0], method="Nelder-Mead",
                          options={"xatol": 0.2, "fatol": 1e-5, "maxiter": 300,
                                   "initial_simplex": np.array([[a0, bx0, by0], [a0 * 1.02, bx0, by0], [a0, bx0 + 6, by0], [a0, bx0, by0 + 6]])})
    a, bx, by = r.x
    fit_iou = -r.fun

    # ---- visibility from the back camera (z-buffer of dense surface samples) ----
    ix = np.clip((a * px_r + bx).astype(int), 0, W - 1)
    iy = np.clip((a * -px_u + by).astype(int), 0, H - 1)
    zbuf = np.full((H, W), -np.inf)
    np.maximum.at(zbuf, (iy, ix), px_f)
    zbuf = nd.maximum_filter(zbuf, size=3)

    V = mesh.vertices
    N = mesh.vertex_normals
    vx = np.clip((a * (V @ right) + bx).astype(int), 0, W - 1)
    vy = np.clip((a * -(V @ up) + by).astype(int), 0, H - 1)
    vf = V @ fwd
    eps = 0.012
    visible = (vf >= zbuf[vy, vx] - eps) & ((N @ fwd) > 0.05) & union[vy, vx]

    # ---- panel labels ----
    # Visible from the back camera: label straight from the back masks.
    # Unseen: nearest visible LEATHER panel. Laces/binding only continue a short distance past
    # the photographed edge (same strand); the AI fuses laces into the surface, so they cannot
    # be told apart geometrically further away (tested: thickness/ray-casting, see RESEARCH_3D.md).
    stack = np.stack([masks.get(k, np.zeros((H, W))) for k in LABELS], -1)
    lab = np.argmax(stack[vy, vx], -1)
    # Only trust mask labels where the surface faces the back camera squarely: at grazing angles
    # small AI-vs-photo misalignments drop lace/binding pixels onto leather.
    known = visible & (stack[vy, vx].max(-1) > 0.5) & ((N @ fwd) > 0.35)
    leather_ids = [LABELS.index(k) for k in ("Base", "BOH", "Fingers", "Palm", "Web", "Welting")]
    unknown = np.where(~known)[0]
    leather_src = known & np.isin(lab, leather_ids)
    _, nl = cKDTree(V[leather_src]).query(V[unknown], k=1)
    lab[unknown] = lab[leather_src][nl]
    for name, reach in (("Laces", 0.012), ("Binding", 0.02)):
        src = known & (lab == LABELS.index(name))
        if src.any():
            d, _ = cKDTree(V[src]).query(V[unknown], k=1)
            lab[unknown[d < reach]] = LABELS.index(name)
    emb = LABELS.index("Embroidery")
    lab[(lab == emb) & ~visible] = LABELS.index("Base")  # embroidery only where photographed

    # Majority filter over mesh neighbours: removes isolated label speckles.
    e = mesh.edges_unique
    for _ in range(4):
        counts = np.zeros((len(V), len(LABELS)), np.int32)
        np.add.at(counts, (e[:, 0], lab[e[:, 1]]), 1)
        np.add.at(counts, (e[:, 1], lab[e[:, 0]]), 1)
        counts[np.arange(len(V)), lab] += 2  # keep own label unless clearly outvoted
        lab = np.argmax(counts, 1)

    colors = np.zeros((len(V), 4), np.uint8)
    colors[:, 0] = lab
    colors[:, 1] = visible.astype(np.uint8) * 255
    colors[:, 3] = 255
    mesh.visual = trimesh.visual.ColorVisuals(mesh, vertex_colors=colors)
    mesh.export(OUT / "glove.glb")

    counts = {LABELS[i]: int((lab == i).sum()) for i in range(len(LABELS)) if (lab == i).any()}
    model = {
        "source": "Hunyuan3D-2mv (Hugging Face Space) from the back/side/palm photos; see RESEARCH_3D.md",
        "vertices": int(len(V)), "faces": int(len(mesh.faces)),
        "labels": LABELS, "labelCounts": counts,
        "visibleFromBack": round(float(visible.mean()), 3),
        "backCamera": {
            "right": right.tolist(), "up": up.tolist(), "forward": fwd.tolist(),
            "scale": float(a), "offset": [float(bx), float(by)],
            "canvas": [W, H], "silhouetteIoU": round(float(fit_iou), 4),
            "forwardRange": [float(px_f.min()), float(px_f.max())],
        },
        "accuracy": "Back side matches the photo; side/palm geometry is AI-estimated (approximate).",
    }
    (OUT / "model.json").write_text(json.dumps(model, indent=2))
    print(json.dumps({k: model[k] for k in ("vertices", "faces", "visibleFromBack", "labelCounts")}, indent=1))
    print("back camera IoU", round(fit_iou, 4))


if __name__ == "__main__":
    main()
